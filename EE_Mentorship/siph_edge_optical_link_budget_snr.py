"""
siph_edge_optical_link_budget_snr.py - Optical Link Budget, Photodiode Responsivity & TIA Noise

Author: Le Dac Anh Tuan (EE Mentorship Program)
Target: Apple Silicon Optical Interconnect / Tesla Dojo Co-Packaged Optics Link
Standard: IEEE 802.3df / OIF-CEI-112G Optical Physical Medium Dependent (PMD)

MATHEMATICAL FOUNDATION & OPTICAL RECEIVER NOISE:
1. Optical Power Link Budget:
   Optical power arriving at the photodiode:

      P_rx_dbm = P_laser_dbm - Loss_total_db

   Where Total Channel Loss accounts for:
   - Input Coupling Loss (Grating Coupler vs Edge Coupler)
   - Modulator Insertion Loss (MZM / MRR)
   - Waveguide Propagation Loss: alpha_db_cm * L_cm
   - WDM Multiplexer & Demultiplexer Filter Insertion Losses
   - Optical Fiber Transmission & Connector Losses
   - Output Photodiode Coupling Loss

2. Germanium Photodiode Quantum Responsivity (R_resp):
   Photocurrent generated per Watt of incident optical power:

                eta_quantum * q * lambda_0
      R_resp = ────────────────────────────  (Amperes / Watt)
                          h * c

   At lambda = 1310 nm with eta = 0.85, R_resp approx 0.90 A/W.
   Signal Photocurrent: I_ph = R_resp * P_rx_optical

3. Transimpedance Amplifier (TIA) Noise & SNR:
   Total RMS noise current:

      sigma_total = sqrt( sigma_shot^2 + sigma_thermal^2 )

   Where:
   - Shot Noise:    sigma_shot^2 = 2 * q * (I_ph + I_dark) * Bandwidth
   - Thermal Noise: sigma_thermal = i_in_referred_density * sqrt(Bandwidth)

4. Eye Q-Factor & Bit Error Rate (BER):
   Signal-to-noise ratio in optical eye diagram:

                 I_ph_1 - I_ph_0
      Q_eye = ─────────────────────
               sigma_1 + sigma_0

   Bit Error Rate: BER approx 0.5 * erfc( Q_eye / sqrt(2) )
   Link Margin: Margin_dB = P_rx_actual_dBm - Sensitivity_dBm
"""

from enum import Enum
from typing import List, Dict, Tuple, Optional
import math


class CouplerType(Enum):
    GRATING_COUPLER = "GRATING_COUPLER"  # Surface vertical coupling (~ 2.5 dB/facet)
    EDGE_COUPLER    = "EDGE_COUPLER"     # Spot-size converter cleave (~ 0.8 dB/facet)


class GermaniumPhotodiode:
    """
    High-Speed Ge-on-Si PIN Photodiode Model.
    """
    Q_ELEC = 1.602176634e-19       # Electron charge (Coulombs)
    PLANCK_H = 6.62607015e-34      # Planck's constant (J*s)
    SPEED_OF_LIGHT = 2.99792458e8  # m/s

    def __init__(
        self,
        wavelength_nm: float = 1310.0,
        quantum_efficiency: float = 0.88,
        dark_current_na: float = 25.0,
        bandwidth_ghz: float = 50.0
    ):
        self.wavelength_m = wavelength_nm * 1e-9
        self.quantum_efficiency = quantum_efficiency
        self.dark_current_a = dark_current_na * 1e-9
        self.bandwidth_hz = bandwidth_ghz * 1e9

        # Theoretical responsivity R = (eta * q * lambda) / (h * c)
        self.responsivity_a_per_w = (
            (self.quantum_efficiency * self.Q_ELEC * self.wavelength_m)
            / (self.PLANCK_H * self.SPEED_OF_LIGHT)
        )

    def compute_photocurrent_a(self, optical_power_w: float) -> float:
        """Computes signal photocurrent generated by incident optical power."""
        return self.responsivity_a_per_w * optical_power_w


class TransimpedanceAmplifierReceiver:
    """
    Linear Transimpedance Amplifier (TIA) & Decision Circuit.
    """
    def __init__(
        self,
        transimpedance_gain_ohms: float = 1200.0,
        input_noise_density_pa_per_rt_hz: float = 14.0,  # 14 pA/sqrt(Hz)
        photodiode: Optional[GermaniumPhotodiode] = None
    ):
        self.gain_ohms = transimpedance_gain_ohms
        self.noise_density_a = input_noise_density_pa_per_rt_hz * 1e-12
        self.pd = photodiode if photodiode else GermaniumPhotodiode()

    def compute_rms_noise_current_a(self, optical_power_w: float) -> float:
        """
        Calculates combined Photodiode Shot Noise + TIA Thermal Noise.
        """
        i_ph = self.pd.compute_photocurrent_a(optical_power_w)
        bw = self.pd.bandwidth_hz

        # 1. Shot noise variance
        var_shot = 2.0 * GermaniumPhotodiode.Q_ELEC * (i_ph + self.pd.dark_current_a) * bw

        # 2. TIA Thermal noise variance
        var_thermal = (self.noise_density_a ** 2) * bw

        total_noise_a = math.sqrt(var_shot + var_thermal)
        return total_noise_a

    def evaluate_ber(self, p_1_w: float, p_0_w: float) -> Tuple[float, float]:
        """
        Computes optical Q-factor and Bit Error Rate (BER).
        Returns (Q_eye, BER).
        """
        i_1 = self.pd.compute_photocurrent_a(p_1_w)
        i_0 = self.pd.compute_photocurrent_a(p_0_w)

        sigma_1 = self.compute_rms_noise_current_a(p_1_w)
        sigma_0 = self.compute_rms_noise_current_a(p_0_w)

        delta_i = i_1 - i_0
        q_eye = delta_i / (sigma_1 + sigma_0) if (sigma_1 + sigma_0) > 0 else 0.0

        # BER = 0.5 * erfc(Q / sqrt(2))
        try:
            ber = 0.5 * math.erfc(q_eye / math.sqrt(2.0))
        except OverflowError:
            ber = 1e-30

        return q_eye, ber


class OpticalLinkBudgetEngine:
    """
    End-to-End Optical Power Link Budget Calculator for Co-Packaged Optics.
    """
    def __init__(self, coupler_type: CouplerType = CouplerType.EDGE_COUPLER):
        self.coupler_type = coupler_type

        # Loss breakdown in dB:
        self.coupler_loss_per_facet_db = 0.8 if coupler_type == CouplerType.EDGE_COUPLER else 2.5
        self.modulator_loss_db = 3.5
        self.waveguide_loss_per_cm_db = 1.8
        self.waveguide_length_cm = 1.5
        self.wdm_mux_loss_db = 1.5
        self.wdm_demux_loss_db = 1.5
        self.fiber_patch_loss_db = 0.4

    def compute_total_channel_loss_db(self) -> float:
        """Sums all optical attenuation sources from Laser to Photodiode."""
        wg_loss = self.waveguide_loss_per_cm_db * self.waveguide_length_cm
        # 2 couplers: Chip-out and Chip-in
        total_coupler_loss = 2.0 * self.coupler_loss_per_facet_db

        total_loss = (
            total_coupler_loss
            + self.modulator_loss_db
            + wg_loss
            + self.wdm_mux_loss_db
            + self.wdm_demux_loss_db
            + self.fiber_patch_loss_db
        )
        return total_loss

    def calculate_link_performance(
        self,
        laser_power_dbm: float = 13.0,  # +13 dBm DFB Laser (~ 20 mW)
        extinction_ratio_db: float = 8.0
    ) -> Dict[str, any]:
        """
        Evaluates optical link power margins, eye opening, and BER.
        """
        loss_total_db = self.compute_total_channel_loss_db()
        p_avg_rx_dbm = laser_power_dbm - loss_total_db
        p_avg_rx_w = (10.0 ** (p_avg_rx_dbm / 10.0)) * 1e-3

        # Extinction ratio: r_er = P_1 / P_0
        r_er = 10.0 ** (extinction_ratio_db / 10.0)
        p_0_w = (2.0 * p_avg_rx_w) / (r_er + 1.0)
        p_1_w = r_er * p_0_w

        pd = GermaniumPhotodiode(wavelength_nm=1310.0, quantum_efficiency=0.88, bandwidth_ghz=50.0)
        receiver = TransimpedanceAmplifierReceiver(transimpedance_gain_ohms=1200.0, photodiode=pd)

        q_eye, ber = receiver.evaluate_ber(p_1_w, p_0_w)

        # Receiver Sensitivity benchmark for BER = 1e-4 (Pre-FEC limit, requires Q = 3.72)
        target_q_fec = 3.72
        # Optical Modulation Amplitude at receiver
        oma_rx_w = p_1_w - p_0_w
        oma_rx_dbm = 10.0 * math.log10(oma_rx_w * 1e3) if oma_rx_w > 0 else -99.0

        # Sensitivity benchmark (approx -12.0 dBm for 50 GHz TIA)
        sensitivity_dbm = -12.0
        link_margin_db = p_avg_rx_dbm - sensitivity_dbm

        return {
            "coupler_type": self.coupler_type.value,
            "total_channel_loss_db": loss_total_db,
            "p_rx_avg_dbm": p_avg_rx_dbm,
            "p_rx_avg_mw": p_avg_rx_w * 1e3,
            "oma_rx_dbm": oma_rx_dbm,
            "photodiode_responsivity_a_per_w": pd.responsivity_a_per_w,
            "q_eye": q_eye,
            "ber": ber,
            "link_margin_db": link_margin_db
        }


def test_optical_link_budget_snr():
    print("================================================================================")
    print("TEST SUITE: OPTICAL LINK POWER BUDGET, GERMANIUM PHOTODIODE & TIA NOISE")
    print("================================================================================")

    # 1. Germanium Photodiode Responsivity
    pd = GermaniumPhotodiode(wavelength_nm=1310.0, quantum_efficiency=0.88)
    print(f"Germanium PIN Photodiode (1310 nm, Quantum Eff = 88%):")
    print(f"  Theoretical Responsivity : {pd.responsivity_a_per_w:.3f} A / W")
    assert 0.90 <= pd.responsivity_a_per_w <= 0.95
    print("[PASS] Milestone 1: Germanium PIN quantum responsivity satisfies theoretical expectation.")

    # 2. Compare Grating Coupler vs Edge Coupler Link Budget
    engine_grating = OpticalLinkBudgetEngine(coupler_type=CouplerType.GRATING_COUPLER)
    engine_edge = OpticalLinkBudgetEngine(coupler_type=CouplerType.EDGE_COUPLER)

    res_grating = engine_grating.calculate_link_performance(laser_power_dbm=13.0, extinction_ratio_db=8.0)
    res_edge = engine_edge.calculate_link_performance(laser_power_dbm=13.0, extinction_ratio_db=8.0)

    print("--------------------------------------------------------------------------------")
    print("OPTICAL POWER BUDGET BENCHMARK (Laser = +13.0 dBm):")
    print(f"  [Grating Coupler] Total Loss: {res_grating['total_channel_loss_db']:.2f} dB | "
          f"P_rx: {res_grating['p_rx_avg_dbm']:.2f} dBm | Margin: {res_grating['link_margin_db']:.2f} dB")
    print(f"  [Edge Coupler   ] Total Loss: {res_edge['total_channel_loss_db']:.2f} dB | "
          f"P_rx: {res_edge['p_rx_avg_dbm']:.2f} dBm | Margin: {res_edge['link_margin_db']:.2f} dB")

    # Edge coupler should save 3.4 dB of optical loss (2 facets * 1.7 dB difference)
    loss_diff = res_grating["total_channel_loss_db"] - res_edge["total_channel_loss_db"]
    assert abs(loss_diff - 3.4) < 1e-3
    print(f"  Edge Coupler Advantage: {loss_diff:.2f} dB optical power saved!")

    # 3. Receiver Eye Q-Factor & BER Performance for Edge Coupler
    print("--------------------------------------------------------------------------------")
    print("RECEIVER TIA NOISE & EYE TELEMETRY (Edge Coupler):")
    print(f"  Optical Q-Factor : {res_edge['q_eye']:.2f}")
    print(f"  Bit Error Rate   : {res_edge['ber']:.6e}")
    print(f"  Link Margin      : {res_edge['link_margin_db']:.2f} dB (Standard requirement >= 3.0 dB)")

    assert res_edge["link_margin_db"] >= 3.0, "Link margin must exceed 3.0 dB for reliable CPO operation"
    assert res_edge["ber"] < 1e-4, "Pre-FEC BER must satisfy optical FEC correction threshold"

    print("[PASS] Milestone BA.3: Optical Link Budget & TIA Noise Model satisfies 112G CPO standard!")
    print("================================================================================")


if __name__ == "__main__":
    test_optical_link_budget_snr()
